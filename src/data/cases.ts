export const CASE_CATEGORIES = ['Образование', 'Процессы и интеграции', 'Боты и ассистенты'] as const;
export type CaseCategory = typeof CASE_CATEGORIES[number];

/** Пара «было → стало». Любое значение может быть маркером. */
export type Metric = { label: string; before: string; after: string };

type CaseBase = {
  slug: string;
  title: string;              // короткий, без маркеров: идёт в <title> и в карточки
  category: CaseCategory;
  service: string;
  industry: string;
  summary: string;            // одно предложение, без маркеров: идёт в description
  color: string;
  symbol: string;
};

/** Кейс одной строкой: страница есть, но в сетке не показывается. */
export type BriefCase = CaseBase & { depth: 'brief'; hidden?: boolean };

export type FullCase = CaseBase & {
  depth: 'full';
  featured?: 1 | 2 | 3;       // позиция на главной
  headline: string[];         // заголовок-результат для h1, строка на элемент
  audience: string;           // для кого, одна строка
  before: string;             // было, 2–3 предложения
  actions: string[];          // что сделали, 3–5 пунктов
  underHood: string;          // технические детали одной строкой
  metrics: Metric[];          // стало — главный блок
  metricsNote?: string;
  next: string;               // что дальше, одна строка
  stack: string[];
  flow: [string, string, string];
};

